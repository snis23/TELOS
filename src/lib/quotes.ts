const EPOCH = "2026-01-01";

/** 날짜("YYYY-MM-DD")마다 하나. 같은 날은 어느 기기에서나 같은 명언 */
export function quoteOfDay(date: string): Quote {
  const n = QUOTES.length;
  const i = ((diffDays(EPOCH, date) % n) + n) % n;
  return QUOTES[i];
}
